#[test]
fn a_wipe_needs_no_operator_of_its_own() {
    // The whole claim of the shape work: mask the incoming layer with a
    // coverage plane and put it over the outgoing one. On the covered side the
    // result is entirely the incoming layer, on the uncovered side entirely
    // the outgoing one, and the pixel the edge passes through is the mix.
    use media_editor_core::Rational;
    use media_editor_render::shape::{Edge, Shape, plane};

    // Over a mid-grey rather than over black. Over black the bottom layer
    // contributes no light at all, so the result is just the masked top layer
    // encoded again -- and the linear-light answer and the code-value answer
    // agree exactly, which is a test that cannot tell them apart. That mistake
    // is already in this project's verification notes once; this is the second
    // place it would have been made.
    let incoming = flat(4, 1, [255, 255, 255, 255]);
    let outgoing = flat(4, 1, [128, 128, 128, 255]);
    let edge = Edge::new(
        Rational::ONE,
        Rational::ZERO,
        Rational::new(5, 2).expect("a rational"),
    )
    .expect("an edge");
    let coverage = plane(&Shape::half_plane(edge).expect("a shape"), 4, 1).expect("a plane");
    assert_eq!(coverage, vec![255, 255, 128, 0]);

    let wiped = over(
        &media_editor_render::composite::masked(&incoming, &coverage).expect("a masked frame"),
        &outgoing,
    )
    .expect("a wipe");
    let samples = wiped.to_packed().expect("samples");
    assert_eq!(&samples[0..4], &[255, 255, 255, 255], "wholly the incoming");
    assert_eq!(
        &samples[12..16],
        &[128, 128, 128, 255],
        "wholly the outgoing"
    );
    assert_eq!(
        samples[15], 255,
        "the programme stays opaque across the edge"
    );
    assert_eq!(samples[11], 255);
    // The edge pixel, worked out by hand. The incoming is white, so its light
    // is 1; masked to a coverage of 128/255 = 0.50196 it becomes light
    // 0.50196 at coverage 128. The grey underneath is stored 128, which is
    // 0.21586 of full light, and 128/255 of coverage leaves 0.49804 of it. So
    // the sum is 0.50196 + 0.21586 x 0.49804 = 0.60947, which encodes to 205.
    //
    // Mixing the code values instead gives 255 x 0.50196 + 128 x 0.49804 =
    // 192. Thirteen code values apart, and the linear answer is the *brighter*
    // one here.
    //
    // Pin the calculated value rather than relying on a brighter/darker rule.
    assert_eq!(samples[8], 205);
    assert_eq!(samples[9], 205);
    assert_eq!(samples[10], 205);
}
