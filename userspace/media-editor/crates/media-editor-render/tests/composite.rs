#[test]
fn the_two_alpha_states_are_not_interchangeable() {
    let straight = frame(&[(10, 20, 30, 200); 4], AlphaState::Straight);
    let premultiplied = premultiply(&straight).expect("premultiplied");
    assert_eq!(
        premultiply(&premultiplied),
        Err(RenderStatus::WrongAlphaState),
        "multiplying twice is not a thing that can be asked for"
    );
    assert_eq!(
        unpremultiply(&straight),
        Err(RenderStatus::WrongAlphaState),
        "nor is dividing out what was never multiplied in"
    );
    assert_eq!(
        over(&straight, &straight),
        Err(RenderStatus::WrongAlphaState),
        "and `over` on straight samples is the bug, not an option"
    );
}

#[test]
fn two_frames_that_are_not_the_same_picture_are_not_layers() {
    // Different geometry, different colour, different pixel aspect: each is a
    // decision somebody has to make before these can be added, and none of
    // them is this operator's to make silently.
    let top = premultiply(&frame(&[(1, 2, 3, 200); 8], AlphaState::Straight)).expect("a frame");

    let narrower =
        premultiply(&frame(&[(1, 2, 3, 200); 4], AlphaState::Straight)).expect("a frame");
    assert_eq!(over(&top, &narrower), Err(RenderStatus::NotComposable));

    let wide = FrameDescription::square(
        Geometry::new(8, 1).expect("a geometry"),
        PixelFormat::Rgba8,
        ColourDescription::new(
            Primaries::Bt2020,
            TransferFunction::PerceptualQuantiser,
            MatrixCoefficients::Identity,
            Range::Full,
        ),
        None,
        Some(AlphaState::Premultiplied),
    )
    .expect("a description");
    let other = Frame::from_packed(wide, &top.to_packed().expect("bytes")).expect("a frame");
    assert_eq!(over(&top, &other), Err(RenderStatus::NotComposable));
}

/// The worst disagreement permitted between the sRGB and the linear route, in
/// each band of 32 sRGB code values. Measured, not guessed: above the midpoint
/// the two routes agree to within a single code value; below it, eight-bit
/// linear runs out of steps.
const BOUND: [i32; 8] = [11, 5, 3, 2, 1, 1, 1, 1];

#[test]
fn compositing_works_in_light_whatever_the_frames_are_encoded_in() {
    // The same two layers, composited in sRGB and in linear, must produce the
    // same *light*. The encodings differ, so the code values must too, but
    // converting one result into the other's description has to land on it.
    // That is what "in linear light and nowhere else" means as a property
    // rather than a slogan: the answer does not depend on the encoding it
    // happened to arrive in.
    //
    // It does not land exactly, and the reason is worth measuring rather than
    // hiding behind one loose tolerance. Eight-bit *linear* has 255 evenly
    // spaced steps of light, and sRGB spends most of its code values in the
    // shadows precisely because the eye does. So the round trip through linear
    // is faithful in the highlights and coarse near black — and the error is
    // bounded per brightness band, which is a statement about the format
    // rather than about this operator.
    let linear_colour = ColourDescription::new(
        Primaries::Bt709,
        TransferFunction::Linear,
        MatrixCoefficients::Identity,
        Range::Full,
    );
    let linear_description = FrameDescription::square(
        Geometry::new(64, 1).expect("a geometry"),
        PixelFormat::Rgba8,
        linear_colour,
        None,
        Some(AlphaState::Premultiplied),
    )
    .expect("a description");

    let mut worst = [0_i32; 8];

    for seed in 11..20 {
        let top = premultiplied_spread(seed);
        let bottom = premultiplied_spread(seed + 40);
        let in_srgb = over(&top, &bottom).expect("a composite");

        let in_linear = over(
            &convert(&top, linear_description).expect("converted"),
            &convert(&bottom, linear_description).expect("converted"),
        )
        .expect("a composite");

        assert_ne!(
            in_srgb.to_packed().expect("bytes"),
            in_linear.to_packed().expect("bytes"),
            "different encodings hold different code values, or this test is \
             comparing a thing with itself"
        );

        let brought_back = convert(&in_linear, *in_srgb.description()).expect("converted");
        for (one, other) in pixels(&brought_back).iter().zip(pixels(&in_srgb).iter()) {
            assert_eq!(one.3, other.3, "coverage survives a conversion unchanged");
            for (mine, theirs) in [(one.0, other.0), (one.1, other.1), (one.2, other.2)] {
                let band = usize::from(theirs) / 32;
                worst[band] = worst[band].max((i32::from(mine) - i32::from(theirs)).abs());
            }
        }
    }

    for (band, (seen, allowed)) in worst.iter().zip(BOUND.iter()).enumerate() {
        assert!(
            seen <= allowed,
            "sRGB codes {}..{} disagree by {seen}, past the {allowed} that \
             eight-bit linear accounts for",
            band * 32,
            band * 32 + 31
        );
    }
    assert!(
        worst[4..].iter().all(|seen| *seen <= 1),
        "above the midpoint the two routes must agree to a code value: {worst:?}"
    );
    assert!(
        worst[0] > worst[7],
        "if the shadows were not the coarse end, this test would be measuring \
         something other than what it claims"
    );
}

#[test]
fn a_conversion_will_not_quietly_change_what_alpha_means() {
    // Gaining alpha, losing it, and re-associating it are three operations
    // with three names. A colour conversion that did any of them silently is
    // how a keyed title arrives opaque — which is exactly what this codebase
    // did until this test was written.
    let premultiplied = premultiplied_spread(21);
    let straight = FrameDescription::square(
        Geometry::new(64, 1).expect("a geometry"),
        PixelFormat::Rgba8,
        srgb(),
        None,
        Some(AlphaState::Straight),
    )
    .expect("a description");
    assert_eq!(
        convert(&premultiplied, straight),
        Err(RenderStatus::ConversionUnavailable),
        "re-associating alpha is `premultiply`'s job, and it has a name"
    );

    let opaque = FrameDescription::square(
        Geometry::new(64, 1).expect("a geometry"),
        PixelFormat::Rgb8,
        srgb(),
        None,
        None,
    )
    .expect("a description");
    assert_eq!(
        convert(&premultiplied, opaque),
        Err(RenderStatus::ConversionUnavailable),
        "dropping coverage is compositing against a background, and that has \
         a name too"
    );
}

#[test]
fn a_conversion_carries_coverage_through_untouched() {
    // Coverage is not light: no transfer function, no gamut matrix, no
    // limited-range scaling. Every alpha byte must arrive on the other side
    // exactly as it left, including the ones that are neither 0 nor 255.
    let source = premultiplied_spread(22);
    let wide = FrameDescription::square(
        Geometry::new(64, 1).expect("a geometry"),
        PixelFormat::Rgba8,
        ColourDescription::new(
            Primaries::Bt2020,
            TransferFunction::PerceptualQuantiser,
            MatrixCoefficients::Identity,
            Range::Full,
        ),
        None,
        Some(AlphaState::Premultiplied),
    )
    .expect("a description");
    let converted = convert(&source, wide).expect("converted");

    let before: std::vec::Vec<u8> = pixels(&source).iter().map(|pixel| pixel.3).collect();
    let after: std::vec::Vec<u8> = pixels(&converted).iter().map(|pixel| pixel.3).collect();
    assert_eq!(before, after);
    assert!(
        before.iter().any(|alpha| *alpha != 0 && *alpha != 255),
        "a test that only saw opaque and clear pixels would have passed \
         against the bug it exists to catch"
    );
    assert_ne!(
        source.to_packed().expect("bytes"),
        converted.to_packed().expect("bytes"),
        "the colour did change, so the alpha was carried rather than skipped"
    );
}

#[test]
fn the_premultiplied_tolerance_is_exactly_one_code_value() {
    // The check allows a re-encoded sample one code value past its exact
    // bound, because changing encodings can move it that far. That tolerance
    // is pinned from both sides here: one over passes, two over does not. A
    // tolerance nobody tests is a tolerance that grows.
    //
    // Coverage 128 in sRGB: the light is 128/255 = 0.50196, and the sRGB code
    // nearest that light is 188. So 189 is the last sample this accepts.
    let ceiling = 188_u8;
    for (offset, accepted) in [(0_u8, true), (1, true), (2, false)] {
        let value = ceiling + offset;
        let candidate = frame(&[(value, 0, 0, 128)], AlphaState::Premultiplied);
        assert_eq!(
            checked_premultiplied(&candidate).is_ok(),
            accepted,
            "a sample {offset} code values past the ceiling"
        );
    }

    // And the bug it exists to catch misses by far more than one.
    let white = frame(&[(255, 255, 255, 128)], AlphaState::Premultiplied);
    assert_eq!(
        checked_premultiplied(&white),
        Err(RenderStatus::NotPremultiplied),
        "full white at half coverage is {} code values past its ceiling",
        255 - ceiling
    );
}

/// A frame of one colour at one coverage, premultiplied, of a given size.
fn flat(width: u32, height: u32, sample: [u8; 4]) -> Frame {
    let description = described(width, height, AlphaState::Premultiplied);
    let mut packed = std::vec::Vec::new();
    for _ in 0..(width as usize * height as usize) {
        packed.extend_from_slice(&sample);
    }
    Frame::from_packed(description, &packed).expect("a frame")
}

#[test]
fn a_mask_at_full_coverage_changes_nothing_at_all() {
    // 255/255 is exactly one, so an unmasked pixel has to arrive unchanged
    // rather than nearly unchanged. A rounding that drifted here would show up
    // as a wipe's untouched side shifting by a code value.
    let frame = flat(4, 2, [200, 100, 50, 255]);
    let masked = media_editor_render::composite::masked(&frame, &[255; 8]).expect("a masked frame");
    assert_eq!(masked, frame);
}

#[test]
fn a_mask_at_no_coverage_leaves_nothing() {
    let frame = flat(2, 2, [200, 100, 50, 255]);
    let masked = media_editor_render::composite::masked(&frame, &[0; 4]).expect("a masked frame");
    assert_eq!(masked.to_packed().expect("samples"), vec![0; 16]);
}

#[test]
fn a_mask_scales_the_coverage_with_the_colour() {
    // Premultiplied, so halving the coverage halves the colour too. A frame
    // whose colour was scaled and whose alpha was not would claim more colour
    // than its coverage allows, and `over` refuses exactly that.
    //
    // But the two are halved in different *spaces*, and that is the whole of
    // what this test pins. A premultiplied sample is `encode(light x
    // coverage)`, so halving it means halving the **light**; coverage is a
    // fraction of a pixel's area and is linear in its stored value, so halving
    // that means halving the byte.
    let frame = flat(1, 1, [200, 100, 50, 255]);
    let masked = media_editor_render::composite::masked(&frame, &[128]).expect("a masked frame");
    // Worked out by hand, one channel at a time, at a coverage of 128/255 =
    // 0.50196:
    //
    //   red   200 decodes to 0.57751; x 0.50196 = 0.28993; encodes to 147
    //   green 100 decodes to 0.12744; x 0.50196 = 0.06397; encodes to  72
    //   blue   50 decodes to 0.03190; x 0.50196 = 0.01601; encodes to  34
    //   alpha 255 x 128 / 255 = 128, exactly
    //
    // The expected values scale linear light before encoding.
    assert_eq!(masked.to_packed().expect("samples"), vec![147, 72, 34, 128]);
    assert!(checked_premultiplied(&masked).is_ok());
}

#[test]
