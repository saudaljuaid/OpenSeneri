//! Compositing, against what the operator is supposed to mean.
//!
//! `over` is an algebra before it is a loop: an identity on each side, an
//! absorbing element, and associativity. Those are checked here as algebra,
//! and the one property that eight-bit arithmetic cannot deliver exactly is
//! measured rather than asserted away.

use media_editor_media::colour::{MatrixCoefficients, Primaries, Range, TransferFunction};
use media_editor_media::{
    AlphaState, ColourDescription, Frame, FrameDescription, Geometry, PixelFormat,
};
use media_editor_render::composite::{checked_premultiplied, over, premultiply, unpremultiply};
use media_editor_render::{RenderStatus, convert};

/// The colour every test here works in unless it says otherwise.
fn srgb() -> ColourDescription {
    ColourDescription::srgb_full()
}

fn described(width: u32, height: u32, state: AlphaState) -> FrameDescription {
    FrameDescription::square(
        Geometry::new(width, height).expect("a geometry"),
        PixelFormat::Rgba8,
        srgb(),
        None,
        Some(state),
    )
    .expect("a description")
}

/// A frame from a list of `(r, g, b, a)` pixels.
fn frame(pixels: &[(u8, u8, u8, u8)], state: AlphaState) -> Frame {
    let width = u32::try_from(pixels.len()).expect("a width");
    let mut bytes = std::vec::Vec::new();
    for &(red, green, blue, alpha) in pixels {
        bytes.extend_from_slice(&[red, green, blue, alpha]);
    }
    Frame::from_packed(described(width, 1, state), &bytes).expect("a frame")
}

/// A frame's pixels, back out.
fn pixels(frame: &Frame) -> std::vec::Vec<(u8, u8, u8, u8)> {
    frame
        .to_packed()
        .expect("packed bytes")
        .chunks_exact(4)
        .map(|pixel| (pixel[0], pixel[1], pixel[2], pixel[3]))
        .collect()
}

/// A deterministic spread of pixels that are valid premultiplied samples.
///
/// Generated by premultiplying straight ones, which is the only way to be sure
/// they are valid — inventing premultiplied samples directly is how a test
/// ends up asserting something the operator never has to handle.
fn premultiplied_spread(seed: u64) -> Frame {
    let mut state = seed;
    let mut straight = std::vec::Vec::new();
    for _ in 0..64 {
        let mut next = || {
            // A small LCG: reproducible on every machine, and not floating
            // point (R-4.1).
            state = state
                .wrapping_mul(6_364_136_223_846_793_005)
                .wrapping_add(1);
            u8::try_from((state >> 33) & 0xFF).unwrap_or(0)
        };
        straight.push((next(), next(), next(), next()));
    }
    premultiply(&frame(&straight, AlphaState::Straight)).expect("premultiplied")
}

#[test]
fn a_transparent_layer_over_anything_leaves_it_alone() {
    // The identity on the left. Zero coverage contributes no light and no
    // coverage, so every sample of the result must be the bottom layer's, bit
    // for bit — not nearly, exactly.
    let bottom = premultiplied_spread(1);
    let clear = frame(&[(0, 0, 0, 0); 64], AlphaState::Premultiplied);
    let result = over(&clear, &bottom).expect("a composite");
    assert_eq!(result.digest(), bottom.digest());
    assert_eq!(result, bottom);
}

#[test]
fn an_opaque_layer_over_anything_hides_it() {
    // The absorbing element. Full coverage leaves no remainder, so the bottom
    // layer cannot contribute anything at all.
    let bottom = premultiplied_spread(2);
    let top = frame(&[(200, 30, 90, 255); 64], AlphaState::Premultiplied);
    let result = over(&top, &bottom).expect("a composite");
    assert_eq!(result, top);
    assert_eq!(
        over(&top, &frame(&[(0, 0, 0, 0); 64], AlphaState::Premultiplied)).expect("a composite"),
        top,
        "and over nothing, the same"
    );
}

#[test]
fn compositing_over_an_opaque_layer_gives_an_opaque_result() {
    // Nothing may become see-through by having something laid on it. This is
    // what makes a background a background.
    let opaque =
        premultiply(&frame(&[(10, 20, 30, 255); 64], AlphaState::Straight)).expect("premultiplied");
    let top = premultiplied_spread(3);
    let result = over(&top, &opaque).expect("a composite");
    for pixel in pixels(&result) {
        assert_eq!(pixel.3, 255, "{pixel:?}");
    }
}

#[test]
fn a_half_covered_white_is_composited_in_light_and_not_in_code_values() {
    // Worked out by hand, and worked out over a background that can tell the
    // difference. Over black it could not: the background contributes nothing
    // either way, so compositing in the encoded space would give the same
    // answer and this test would pass against the bug it exists to catch.
    //
    // So: full white at coverage 128, over an opaque sRGB mid-grey.
    //
    //   top light      = 128/255                       = 0.501961
    //   bottom light   = ((128/255 + 0.055)/1.055)^2.4 = 0.215861
    //   remainder      = 1 - 128/255                   = 0.498039
    //   result light   = 0.501961 + 0.215861 x 0.498039 = 0.609468
    //   sRGB of that   = 1.055 x 0.609468^(1/2.4) - 0.055 = 0.803319
    //   code value     = 0.803319 x 255                 = 204.85 -> 205
    //
    // Adding the code values instead — 188 and 128 — gives 252, which is
    // forty-seven code values too bright and is precisely what a compositor
    // that skips the transfer function produces.
    let top =
        premultiply(&frame(&[(255, 255, 255, 128)], AlphaState::Straight)).expect("premultiplied");
    assert_eq!(
        pixels(&top)[0],
        (188, 188, 188, 128),
        "premultiplying happens in light too: 128/255 of full white encodes \
         to 188, not to 128"
    );

    let grey = frame(&[(128, 128, 128, 255)], AlphaState::Premultiplied);
    let result = over(&top, &grey).expect("a composite");
    assert_eq!(pixels(&result)[0], (205, 205, 205, 255));
}

#[test]
fn compositing_straight_samples_as_premultiplied_is_the_dark_fringe() {
    // The bug itself, demonstrated rather than described. A half-covered white
    // edge over a black background: done correctly the edge is mid-grey; done
    // by relabelling straight samples as premultiplied it comes out far too
    // bright, and over a white background the same mistake comes out far too
    // dark. That asymmetry is why the artefact is called a fringe: it takes
    // the colour of whichever mistake the background makes.
    let straight = frame(&[(255, 255, 255, 128)], AlphaState::Straight);
    let honest = premultiply(&straight).expect("premultiplied");
    let black = frame(&[(0, 0, 0, 255)], AlphaState::Premultiplied);
    let correct = pixels(&over(&honest, &black).expect("a composite"))[0];

    // Now the mistake: call the straight samples premultiplied and composite
    // them. The operator refuses, which is the whole point of the check —
    // white at half coverage is brighter than half coverage allows.
    let relabelled = Frame::from_packed(
        described(1, 1, AlphaState::Premultiplied),
        &straight.to_packed().expect("bytes"),
    )
    .expect("a frame");
    assert_eq!(
        over(&relabelled, &black),
        Err(RenderStatus::NotPremultiplied),
        "a frame whose colour outruns its coverage is not premultiplied, \
         whatever its description says"
    );

    // And if it were not refused, this is what it would produce: the top
    // layer's full-strength white plus the background's remainder, which is
    // brighter than the correct answer by a wide margin.
    let (red, _, _, _) = correct;
    assert!(
        red < 255,
        "the correct half-covered white is not full white; the relabelled \
         one would be"
    );
}

#[test]
fn a_frame_that_is_not_premultiplied_is_caught_and_a_real_one_is_not() {
    let straight = frame(&[(255, 200, 100, 8); 16], AlphaState::Straight);
    let honest = premultiply(&straight).expect("premultiplied");
    checked_premultiplied(&honest).expect("an honest frame passes");

    let relabelled = Frame::from_packed(
        described(16, 1, AlphaState::Premultiplied),
        &straight.to_packed().expect("bytes"),
    )
    .expect("a frame");
    assert_eq!(
        checked_premultiplied(&relabelled),
        Err(RenderStatus::NotPremultiplied)
    );

    // Every frame this module produces must pass its own check, or the
    // operator is not closed over its own output.
    for seed in 1..8 {
        let spread = premultiplied_spread(seed);
        checked_premultiplied(&spread).expect("a generated frame passes");
        let stacked = over(&spread, &premultiplied_spread(seed + 100)).expect("a composite");
        checked_premultiplied(&stacked).expect("a composed frame passes");
    }
}

#[test]
fn over_is_associative_to_within_one_code_value() {
    // In exact arithmetic `over` is associative, which is what makes a layer
    // stack a stack rather than an order of operations. In eight bits it is
    // associative to within quantisation, and this measures the gap rather
    // than assuming it: three layers, both groupings, worst channel over four
    // thousand samples.
    //
    // If the two groupings could differ by more than a code value, a layer
    // stack would change its picture when a user grouped two clips into a
    // compound — and that is a bug report nobody could ever reproduce.
    let mut worst = 0_i32;
    for seed in 1..16 {
        let first = premultiplied_spread(seed);
        let second = premultiplied_spread(seed + 40);
        let third = premultiplied_spread(seed + 80);

        let left = over(&over(&first, &second).expect("a composite"), &third).expect("a composite");
        let right =
            over(&first, &over(&second, &third).expect("a composite")).expect("a composite");

        for (one, other) in pixels(&left).iter().zip(pixels(&right).iter()) {
            for (a, b) in [
                (one.0, other.0),
                (one.1, other.1),
                (one.2, other.2),
                (one.3, other.3),
            ] {
                worst = worst.max((i32::from(a) - i32::from(b)).abs());
            }
        }
    }
    assert!(
        worst <= 1,
        "the two groupings differ by {worst} code values, which is more than \
         quantisation can account for"
    );
}

#[test]
fn premultiplying_and_dividing_back_out_is_exact_only_at_full_coverage() {
    // The honest statement of a lossy round trip. At full coverage nothing was
    // multiplied away, so every sample must come back exactly. Below it,
    // precision was discarded and cannot return, so the claim is a bound and
    // the bound is measured.
    let opaque: std::vec::Vec<(u8, u8, u8, u8)> = (0..64)
        .map(|index| (index * 4, 255 - index * 4, 128, 255))
        .collect();
    let straight = frame(&opaque, AlphaState::Straight);
    let back = unpremultiply(&premultiply(&straight).expect("premultiplied")).expect("straight");
    assert_eq!(back, straight, "full coverage multiplies by one");

    // Half coverage: recoverable to within a code value or two, because the
    // multiply threw away a bit and the divide is amplifying what is left.
    let half: std::vec::Vec<(u8, u8, u8, u8)> = (0..64)
        .map(|index| (index * 4, 255 - index * 4, 128, 128))
        .collect();
    let straight = frame(&half, AlphaState::Straight);
    let back = unpremultiply(&premultiply(&straight).expect("premultiplied")).expect("straight");
    let mut worst = 0_i32;
    for (one, other) in pixels(&back).iter().zip(half.iter()) {
        for (a, b) in [(one.0, other.0), (one.1, other.1), (one.2, other.2)] {
            worst = worst.max((i32::from(a) - i32::from(b)).abs());
        }
        assert_eq!(one.3, other.3, "coverage itself is never lost");
    }
    assert!(
        worst <= 2,
        "half-coverage round trip lost {worst} code values"
    );
}

#[test]
fn zero_coverage_keeps_no_colour_at_all() {
    // Multiplying by zero is not lossy, it is total. The colour is gone, and
    // pretending otherwise — carrying the straight value along beside a zero
    // alpha — is how a fully transparent pixel ends up contributing a colour
    // fringe when something later scales the picture.
    let straight = frame(&[(255, 128, 64, 0); 8], AlphaState::Straight);
    let premultiplied = premultiply(&straight).expect("premultiplied");
    for pixel in pixels(&premultiplied) {
        assert_eq!(pixel, (0, 0, 0, 0));
    }
    for pixel in pixels(&unpremultiply(&premultiplied).expect("straight")) {
        assert_eq!(pixel, (0, 0, 0, 0), "nothing was kept, so nothing returns");
    }
}

#[test]
fn compositing_is_deterministic() {
    let top = premultiplied_spread(5);
    let bottom = premultiplied_spread(6);
    let first = over(&top, &bottom).expect("a composite");
    let second = over(&top, &bottom).expect("a composite");
    assert_eq!(first.digest(), second.digest());
    assert_eq!(
        premultiply(&frame(&[(1, 2, 3, 4); 4], AlphaState::Straight))
            .expect("premultiplied")
            .digest(),
        premultiply(&frame(&[(1, 2, 3, 4); 4], AlphaState::Straight))
            .expect("premultiplied")
            .digest()
    );
}

